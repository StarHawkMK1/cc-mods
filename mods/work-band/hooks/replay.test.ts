import { expect, test } from 'claude-code/testing'

import { replay, signalsOf } from './replay'
import { TRANSCRIPT, back, said, used, user } from './transcript-fixture'

const OPTS = { skills: [], tests: [], at: 9_000 }

test('a superpowers flow comes back with its stage, title, tasks and test', () => {
  const { work, planPath } = replay(TRANSCRIPT, OPTS)
  expect(work.flow).toMatchObject({ stage: 'build', isFinished: false, topic: 'Auth redesign', specTitle: 'Auth redesign', planTitle: 'Auth login', planTasks: 7 })
  expect(work.todos.filter(t => t.status === 'completed')).toHaveLength(3)
  expect(work.test).toEqual({ isPass: false, at: 0 })
  expect(work.since).toBe(9_000)
  expect(work.isReplayed).toBe(true)
  expect(work.clock).toBeUndefined()
  expect(work.skill).toBeUndefined()
  expect(planPath).toBeUndefined()
})

test('signalsOf: requests, slash skills, tools and answers; skill bodies and notices are not prompts', () => {
  const kinds = signalsOf([
    ...TRANSCRIPT.slice(0, 4),
    user('<task-notification>agent done</task-notification>'),
    user('<system-reminder>x</system-reminder>'),
    user('<command-name>/model</command-name>\n<command-args>opus</command-args>'),
    user('Caveat: The messages below were generated by the user while running local commands.'),
  ]).map(s => s.kind)
  expect(kinds).toEqual(['request', 'slash', 'answer', 'request'])
})

test('Finish ends after the reply’s turn; a built-in command is not the reply', () => {
  const asked = [user('<command-name>/superpowers:finishing-a-development-branch</command-name>'), said('1. Merge 2. PR 3. Keep?')]
  expect(replay([...asked, user('<command-name>/model</command-name>'), said('Set model.')], OPTS).work.flow?.isFinished).toBe(false)
  const merged = [...asked, user('1'), used('Bash', { command: 'git merge feat' }), back(), said('Merged.')]
  expect(replay(merged, OPTS).work.flow?.isFinished).toBe(true)
  expect(replay([...merged, user('thanks')], OPTS).work.flow).toBeNull()
})

test('in Finish, the next prompt ends the reply’s turn even when that turn only called tools', () => {
  const asked = [user('<command-name>/superpowers:finishing-a-development-branch</command-name>'), said('1. Merge 2. PR 3. Keep?')]
  const toolsOnly = [...asked, user('1'), used('Bash', { command: 'git merge feat' }), back()]
  expect(replay(toolsOnly, OPTS).work.flow?.isFinished).toBe(false)
  expect(replay([...toolsOnly, user('next thing')], OPTS).work.flow).toBeNull()
})

test('errored or failed calls change nothing; TaskCreate takes its id from the result', () => {
  const { work } = replay(
    [
      user('do it'),
      used('Skill', { skill: 'superpowers:brainstorming', args: 'X' }, { isError: true }),
      used('Skill', { skill: 'superpowers:writing-plans' }, { result: { success: false } }),
      used('TaskCreate', { subject: 'Run tests' }, { result: { task: { id: '4' } } }),
      used('TaskUpdate', { taskId: '4', status: 'in_progress' }),
    ],
    OPTS,
  )
  expect(work.flow).toBeNull()
  expect(work.todos).toEqual([{ id: '4', title: 'Run tests', status: 'in_progress' }])
})

test('a harness run keeps an unfinished list but no test, and drops a finished one', () => {
  const run = (status: string) => replay([user('fix it'), used('TodoWrite', { todos: [{ content: 'A', status }] }), used('Bash', { command: 'npm test' })], OPTS).work
  expect(run('in_progress').todos).toHaveLength(1)
  expect(run('in_progress').test).toBeUndefined()
  expect(run('completed').todos).toEqual([])
})

test('a plan named in the Build skill but not written in the transcript is handed back to read', () => {
  const { planPath } = replay([user('go'), used('Skill', { skill: 'superpowers:executing-plans', args: 'docs/superpowers/plans/old.md' })], OPTS)
  expect(planPath).toBe('docs/superpowers/plans/old.md')
})

test('odd transcripts', () => {
  expect(replay(undefined, OPTS).work.flow).toBeNull()
  expect(replay([null, 7, { role: 'assistant' }, { role: 'user', text: 42 }], OPTS).work.todos).toEqual([])
})

test('a long transcript with large writes is folded to the end', () => {
  const big = 'x'.repeat(20_000)
  const rows = [
    user('<command-name>/superpowers:brainstorming</command-name>\n<command-args>Long one</command-args>'),
    ...Array.from({ length: 4_090 }, (_, i) => used('Write', { file_path: `notes/n${i}.md`, content: big })),
    used('Write', { file_path: 'docs/superpowers/specs/x.md', content: '# Long one 설계\n' }),
  ]
  expect(replay(rows, OPTS).work.flow).toMatchObject({ stage: 'build', specTitle: 'Long one' })
})
